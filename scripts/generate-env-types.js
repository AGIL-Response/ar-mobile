const fs = require('fs');
const path = require('path');

/**
 * Generates TypeScript types from .env files
 * This script reads .env.dev and .env.pro and generates the EnvVars interface
 */

const projectRoot = path.resolve(__dirname, '..');
const envDevPath = path.join(projectRoot, '.env.dev');
const envProPath = path.join(projectRoot, '.env.pro');
const outputPath = path.join(projectRoot, 'constants', 'env-types.ts');

function parseEnvFile(filePath) {
  const envVars = new Set();
  
  if (!fs.existsSync(filePath)) {
    return envVars;
  }
  
  const content = fs.readFileSync(filePath, 'utf8');
  const lines = content.split('\n');
  
  lines.forEach((line) => {
    const trimmedLine = line.trim();
    // Skip comments and empty lines
    if (trimmedLine && !trimmedLine.startsWith('#')) {
      const match = trimmedLine.match(/^([^=]+)=/);
      if (match) {
        const key = match[1].trim();
        envVars.add(key);
      }
    }
  });
  
  return envVars;
}

// Parse both env files and merge unique keys
const devVars = parseEnvFile(envDevPath);
const proVars = parseEnvFile(envProPath);
const allVars = new Set([...devVars, ...proVars]);

// Sort for consistent output
const sortedVars = Array.from(allVars).sort();

// Generate TypeScript interface
const interfaceContent = `/**
 * Auto-generated TypeScript types for environment variables
 * DO NOT EDIT THIS FILE MANUALLY
 * 
 * This file is generated by scripts/generate-env-types.js
 * Run 'npm run generate:env-types' to regenerate
 */

export interface EnvVars {
${sortedVars.map(key => `  ${key}?: string;`).join('\n')}
  [key: string]: string | undefined;
}
`;

// Write the generated file
fs.writeFileSync(outputPath, interfaceContent, 'utf8');

console.log(`✅ Generated env types with ${sortedVars.length} variables:`);
sortedVars.forEach(key => console.log(`   - ${key}`));

